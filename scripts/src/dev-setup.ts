import { execSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * pnpm dev:setup — local only. Reads `supabase status` and fills the repo-root .env so the local
 * Supabase stack acts as both the control plane and the "dev" tenant. Existing values are kept.
 * Never run against a shared or production project.
 */

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const envPath = path.join(root, '.env');

function readEnv(): Map<string, string> {
  const map = new Map<string, string>();
  if (!existsSync(envPath)) return map;
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (m) map.set(m[1]!, m[2]!);
  }
  return map;
}

const status = JSON.parse(
  execSync('pnpm exec supabase status -o json', {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }),
) as Record<string, string>;

const dbUrl = status.DB_URL;
const apiUrl = status.API_URL;
if (!dbUrl || !apiUrl)
  throw new Error('Local Supabase is not running. Run `pnpm supabase start` first.');
if (!/127\.0\.0\.1|localhost/.test(dbUrl))
  throw new Error('Refusing: dev:setup only targets local Supabase');

const env = readEnv();
const defaults: Record<string, string> = {
  CONTROL_DATABASE_URL: dbUrl,
  MASTER_KEY: randomBytes(32).toString('base64'),
  CONTROL_SUPABASE_URL: apiUrl,
  TENANT_DB_URL: dbUrl,
  TENANT_SUPABASE_URL: apiUrl,
  TENANT_ANON_KEY: status.ANON_KEY ?? status.PUBLISHABLE_KEY ?? '',
  TENANT_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY ?? status.SECRET_KEY ?? '',
  PLATFORM_BASE_DOMAIN: 'hrportal.lk',
};
const added: string[] = [];
for (const [k, v] of Object.entries(defaults)) {
  if (!env.has(k)) {
    env.set(k, v);
    added.push(k);
  }
}
writeFileSync(
  envPath,
  `# Local development (generated by pnpm dev:setup). Gitignored. Never commit.\n${[...env]
    .map(([k, v]) => `${k}=${v}`)
    .join('\n')}\n`,
);
console.log(added.length ? `✔ .env: added ${added.join(', ')}` : '✔ .env already complete');
